    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        try {
            String tituloSeleccionado = (String) comboActividades.getSelectedItem();
            logic.Socio socioActual = gui.VentanaSocio.socioLogueado;

            if (tituloSeleccionado == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Tienes que elegir una reserva para borrar alguna");
                return;
            }

            logic.Reserva reservaABorrar = null;
            for (logic.Reserva r : gimnasio.getReservas()) {
                if (r.getActividad().getTitulo().equals(tituloSeleccionado)
                        && r.getSocio().getCorreo().equals(socioActual.getCorreo())) {
                    reservaABorrar = r;
                    break;
                }
            }

            if (reservaABorrar != null) {
                gimnasio.getReservas().remove(reservaABorrar);
                gimnasio.guardarDatos();
                javax.swing.JOptionPane.showMessageDialog(this, "Tu reserva se ha borrado correctamente");
                cargarComboReservas();
                mostrarMisReservas();
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al eliminar tu reserva: " + e.getMessage());
        }

    }//GEN-LAST:event_btnBorrarActionPerformed

