    public void mostrarMisReservas() {
        listadoReservas.setText("");

        logic.Socio socioActual = gui.VentanaSocio.socioLogueado;

        for (logic.Reserva r : gimnasio.getReservas()) {

            if (r.getSocio().getCorreo().equals(socioActual.getCorreo())) {
                listadoReservas.append("Título: " + r.getActividad().getTitulo() + "\n"
                        + "Fecha: " + r.getFechaClase() + "\n"
                        + "Horario: " + r.getActividad().getHorarioInicio() + " - " + r.getActividad().getHorarioFin() + "\n"
                        + "---------------------------------------------\n");
            }
        }
    }

    public void cargarComboReservas() {
        comboActividades.removeAllItems();
        logic.Socio socioActual = gui.VentanaSocio.socioLogueado;

        for (logic.Reserva r : gimnasio.getReservas()) {
            if (r.getSocio().getCorreo().equals(socioActual.getCorreo())) {
                comboActividades.addItem(r.getActividad().getTitulo());
            }
        }
    }

