    private void btnBorrarActividadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActividadActionPerformed
        String nombre = nombreActividad.getText();
        Actividad encontrada = null;

        for (Actividad a : gimnasio.getActividades()) {
            if (a.getTitulo().equalsIgnoreCase(nombre)) {
                encontrada = a;
                break;
            }
        }

        if (encontrada != null) {

            int respuesta = javax.swing.JOptionPane.showConfirmDialog(this, "¿Estas seguro de que quieres borrar la actividad " + nombre + "?");

            if (respuesta == 0) {//(si)
                gimnasio.getActividades().remove(encontrada);
                gimnasio.guardarDatos();
                mostrarListaActividades();
                javax.swing.JOptionPane.showMessageDialog(this, "Has eliminado la actividad " + nombre);
                nombreActividad.setText("");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró la actividad");
        }
    }//GEN-LAST:event_btnBorrarActividadActionPerformed


