    private void btnModificarActividadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActividadActionPerformed

        String nombre = nombreActividad.getText();

        Actividad encontrada = null;
        for (Actividad a : gimnasio.getActividades()) {
            if (a.getTitulo().equalsIgnoreCase(nombre)) {
                encontrada = a;
                break;
            }
        }

        if (encontrada != null) {
            ModificaActividadAdmin mod = new ModificaActividadAdmin(gimnasio, encontrada);
            mod.setVisible(true);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró la actividad");
        }

    }//GEN-LAST:event_btnModificarActividadActionPerformed

