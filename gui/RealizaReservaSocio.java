    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String tituloAct = (String) comboActividades.getSelectedItem();
            Socio socioActual = VentanaSocio.socioLogueado;

            if (tituloAct == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Tienes que elegir la actividad que quieres reservar");
                return;
            }

            Actividad actEncontrada = null;
            for (Actividad a : gimnasio.getActividades()) {
                if (a.getTitulo().equals(tituloAct)) {
                    actEncontrada = a;
                }
            }

            java.time.LocalDate fecha = java.time.LocalDate.now();

            double importe = 0.0;
            if (actEncontrada instanceof ActividadEspecial) {
                importe = ((ActividadEspecial) actEncontrada).getPrecio();
            }

            boolean resultado = gimnasio.realizarReserva(actEncontrada, socioActual, fecha, importe);

            if (resultado) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Reserva hecha, tu ticket de reserva se ha generado");
                VentanaSocio vent = new VentanaSocio(gimnasio);
                vent.setVisible(true);
                this.dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Aforo completo");
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }

    }//GEN-LAST:event_btnGuardarActionPerformed

