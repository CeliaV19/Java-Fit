    private void mostrarDiasActividad() {
        comboDias.removeAllItems();
        String titulo = (String) comboActividades.getSelectedItem();
        if (titulo == null) {
            return;
        }
        for (Actividad a : gimnasio.getActividades()) {
            if (a.getTitulo().equals(titulo)) {
                String[] dias = a.getDiasSemana().split(",");
                for (String d : dias) {
                    comboDias.addItem(d.trim());
                }

            }
        }
    }

